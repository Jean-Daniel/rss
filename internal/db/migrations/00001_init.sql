-- Single-row table holding instance-wide settings.
CREATE TABLE settings (
    id            boolean PRIMARY KEY DEFAULT true CHECK (id),
    password_hash text,
    updated_at    timestamptz NOT NULL DEFAULT now()
);
INSERT INTO settings (id) VALUES (true);

-- Login sessions. Only a SHA-256 of the cookie token is stored, so a copy of
-- the database does not give access to live sessions.
CREATE TABLE sessions (
    token_hash   bytea PRIMARY KEY,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    expires_at   timestamptz NOT NULL,
    user_agent   text NOT NULL DEFAULT ''
);
CREATE INDEX sessions_expires_at ON sessions (expires_at);

CREATE TABLE favicons (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url        text NOT NULL UNIQUE,
    mime_type  text NOT NULL,
    data       bytea NOT NULL,
    fetched_at timestamptz NOT NULL DEFAULT now()
);

-- Display options on groups and feeds: NULL means "use the global preference".
CREATE TABLE groups (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             text NOT NULL,
    show_excerpts     boolean,
    show_images       boolean,
    oldest_first      boolean,
    show_unread_count boolean
);

CREATE TABLE feeds (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url               text NOT NULL UNIQUE,
    title             text NOT NULL DEFAULT '',
    site_url          text NOT NULL DEFAULT '',
    favicon_id        bigint REFERENCES favicons (id) ON DELETE SET NULL,
    auth_username     text,
    auth_password     text,
    show_excerpts     boolean,
    show_images       boolean,
    oldest_first      boolean,
    show_unread_count boolean,
    etag              text,
    last_modified     text,
    last_fetched_at   timestamptz,
    last_new_item_at  timestamptz,
    next_fetch_at     timestamptz NOT NULL DEFAULT now(),
    error_count       integer NOT NULL DEFAULT 0,
    last_error        text,
    created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX feeds_next_fetch_at ON feeds (next_fetch_at);
CREATE INDEX feeds_favicon_id ON feeds (favicon_id);

-- A feed can belong to several groups.
CREATE TABLE feed_groups (
    feed_id  bigint NOT NULL REFERENCES feeds (id) ON DELETE CASCADE,
    group_id bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    PRIMARY KEY (feed_id, group_id)
);
CREATE INDEX feed_groups_group_id ON feed_groups (group_id);

CREATE TABLE items (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id          bigint NOT NULL REFERENCES feeds (id) ON DELETE CASCADE,
    guid             text NOT NULL,
    url              text NOT NULL DEFAULT '',
    title            text NOT NULL DEFAULT '',
    author           text NOT NULL DEFAULT '',
    -- Sanitized HTML, safe to render.
    content          text NOT NULL DEFAULT '',
    published_at     timestamptz NOT NULL,
    added_at         timestamptz NOT NULL DEFAULT now(),
    read_at          timestamptz,
    saved_at         timestamptz,
    -- Bumped whenever read_at or saved_at changes, for syncing other devices.
    state_changed_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (feed_id, guid)
);
-- Item lists are read newest first and paged by (published_at, id).
CREATE INDEX items_stream ON items (published_at DESC, id DESC);
CREATE INDEX items_feed_stream ON items (feed_id, published_at DESC, id DESC);
CREATE INDEX items_unread_stream ON items (published_at DESC, id DESC) WHERE read_at IS NULL;
CREATE INDEX items_unread_feed ON items (feed_id) WHERE read_at IS NULL;
CREATE INDEX items_saved ON items (saved_at DESC, id DESC) WHERE saved_at IS NOT NULL;
CREATE INDEX items_state_changed_at ON items (state_changed_at);

